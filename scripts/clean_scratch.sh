#!/usr/bin/env bash
# Reclaim disk space from benchmark and fixture run output.
#
# Benchmark and catalog fixtures write into bind mounted run directories from
# inside containers. Some of those containers have to run as uid 0 (the open
# source Unity Catalog image is built for its own user and its storage roots must
# be writable), so the files they produce belong to root and a normal user cannot
# unlink them even though the parent directory is owned by the user. Deleting the
# parent fails with "Permission denied" on every child.
#
# This script takes ownership back, then removes the generated trees. Nothing it
# deletes is source: every path below is either gitignored run output or a build
# directory that is regenerated by the toolchain.
#
# Usage:
#   ./scripts/clean_scratch.sh            # run output only, keeps build caches
#   ./scripts/clean_scratch.sh --builds   # also remove cargo, maven, and JNI builds
#   ./scripts/clean_scratch.sh --fixtures # also remove data/ table fixtures
#
# The datasets themselves are not touched. They live outside the repository, at
# ~/data/datasets on the spinning disk.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${REPO_ROOT}"

WITH_BUILDS=0
WITH_FIXTURES=0
for arg in "$@"; do
    case "${arg}" in
        --builds) WITH_BUILDS=1 ;;
        --fixtures) WITH_FIXTURES=1 ;;
        -h|--help) sed -n '2,24p' "${BASH_SOURCE[0]}"; exit 0 ;;
        *) echo "unknown option: ${arg}"; exit 2 ;;
    esac
done

# A harness or build writing while we delete is how artifacts get corrupted.
# The bracket trick keeps the pattern from matching this script's own command line.
if pgrep -af "[r]un_neurips_bigann|[b]uild_three_tier|[c]argo (build|test|clippy)|[r]ustc" >/dev/null; then
    echo "REFUSING: a build or harness is running."
    pgrep -af "[r]un_neurips_bigann|[b]uild_three_tier|[c]argo (build|test|clippy)|[r]ustc"
    exit 1
fi

TARGETS=()
shopt -s nullglob
for d in benchmarks/scratch_*; do TARGETS+=("${d}"); done
if [[ "${WITH_BUILDS}" -eq 1 ]]; then
    TARGETS+=(target target-jni fuzz/target server/flight_sql/target)
    TARGETS+=(tests/iceberg_rust_oracle/target spark-benostreamdb/target trino-benostreamdb/target)
fi
if [[ "${WITH_FIXTURES}" -eq 1 ]]; then
    for d in data/*; do TARGETS+=("${d}"); done
fi
shopt -u nullglob

if [[ ${#TARGETS[@]} -eq 0 ]]; then
    echo "Nothing to remove."
    exit 0
fi

echo "--> Before:"
df -h . | tail -1
echo "--> Targets:"
du -sh "${TARGETS[@]}" 2>/dev/null || true

# Take ownership of anything a container wrote as root, so the removals below do
# not stop at the first root owned child.
ROOT_OWNED=$(find "${TARGETS[@]}" -user root 2>/dev/null | wc -l)
if [[ "${ROOT_OWNED}" -gt 0 ]]; then
    echo "--> ${ROOT_OWNED} path(s) are root owned, from container runs. Reclaiming them needs sudo."
    sudo chown -R "$(id -u):$(id -g)" "${TARGETS[@]}"
fi

rm -rf "${TARGETS[@]}"

echo "--> After:"
df -h . | tail -1
echo "Done. Build caches and fixtures rebuild on demand:"
echo "    cargo build --release -p benostreamdb-flight   # service binary"
echo "    ./scripts/build_connectors.sh                  # maven connector targets"
echo "    .venv/bin/python scripts/build_three_tier.py   # data/three_tier_db"
